<?php

// this file realizes the Parsifal Special Page Resetting the entire system

require_once (  dirname(__FILE__) . "/../config/config.php");    // include path configuration

class ParsifalReset extends FormSpecialPage {

  /** @var bool $VERBOSE  CAVE: if we debug this and set this to true we MUST deselect the "logs" task or we will not see what we log !! */
  private $VERBOSE = false;

  /** @var array $done  human readable results of the tasks executed in onSubmit, displayed by onSuccess */
  private $done = [];

  public function __construct () {;
    parent::__construct( 'ParsifalReset', 'resetParsifal' ); }

  public function getGroupName() {return 'dante';}

  /**
   * Return the list of available reset tasks.
   *
   * @return array  map from task key to label shown next to the checkbox
   */
  private function getTasks () {
    return [
      'apcu'     => 'Clear APCu cache',
      'cache'    => 'Clear Parsifal cache files (_pc_pdflatex files, minted temp files and _minted / _minted- directories in CACHE_PATH)',
      'logs'     => 'Clear log files (Parsifal log and logs of DantePresentations, DanteLinks, DanteTree)',
      'sidebar'  => 'Clear sidebar cache',
      'opcache'  => 'Clear PHP opcache',
      'settings' => 'Touch LocalSettings.php (invalidates MediaWiki caches)',
    ];
  }

  /**
   * Define the form: one checkbox per task, all checked by default.
   *
   * @return array  HTMLForm field descriptor
   */
  public function getFormFields()  {
    $tasks = $this->getTasks();
    return [
      'tasks' => [
        'type'    => 'multiselect',
        'options' => array_flip( $tasks ),                                                                      // HTMLForm expects label => value
        'default' => array_keys( $tasks ),                                                                      // all tasks checked by default
      ],
    ];
  }

  /**
   * Execute the selected tasks.
   *
   * @param array $data  form data; $data['tasks'] holds the keys of the selected tasks
   * @return bool|string  true on success, false or an error message otherwise
   */
  public function onSubmit( array $data )  {
    if (! $this->getUser()->isAllowed ("resetParsifal") ) {return false;}                                       // check for permission "resetParsifal" BEFORE doing anything

    $selected = $data['tasks'] ?? [];
    if ( empty ($selected) ) { return 'No task selected.'; }                                                    // nothing to do

    // dispatch each selected task in the order of getTasks
    foreach ( array_keys( $this->getTasks() ) as $task ) {
      if ( !in_array( $task, $selected, true ) ) { continue; }
      switch ( $task ) {
        case 'apcu':     $this->clearApcu();      break;
        case 'cache':    $this->clearCacheDir();  break;
        case 'logs':     $this->clearLogs();      break;
        case 'sidebar':  $this->clearSidebar();   break;
        case 'opcache':  $this->clearOpcache();   break;
        case 'settings': $this->touchSettings();  break;
      }
    }
    return true;
  }

  /**
   * Show the results of the executed tasks.
   *
   * @return void
   */
  public function onSuccess() {
    $items = '';
    foreach ( $this->done as $line ) { $items .= Html::element( 'li', [], $line ); }                            // one list item per task result
    $this->getOutput()->addHTML( Html::rawElement( 'ul', [], $items ) );
  }

  /**
   * TASK: Clear the APCu cache.
   *
   * @return void
   */
  private function clearApcu () {
    if ( !function_exists( 'apcu_clear_cache' ) ) { $this->done[] = 'APCu: not available'; return; }
    $this->done[] = 'APCu: ' . ( apcu_clear_cache() ? 'cleared' : 'FAILED' );
  }

  /**
   * Decide whether a directory directly in CACHE_PATH is a minted cache directory which may be cleared.
   *
   * @param string $name  file name of the directory (no path)
   * @return bool         true for "_minted" (minted v3) and "_minted-<jobname>" (minted v2)
   */
  private static function isMintedCacheDir ( string $name ) : bool {
    return $name === "_minted" || str_starts_with ($name, "_minted-");
  }

  /**
   * Decide whether a file directly in CACHE_PATH was generated by Parsifal or minted and may be deleted.
   *
   * @param string $name  file name (no path)
   * @return bool         true for Parsifal output files and for leftover minted v3 temporary files
   */
  private static function isCacheFile ( string $name ) : bool {
    if ( str_contains ($name, "_pc_pdflatex") ) { return true; }                                               // Parsifal output: <hash>_pc_pdflatex.{tex,log,pdf,png,...}
    return preg_match ('/^_[0-9A-F]{32}\.(data|config)\.minted$/', $name) === 1;                             // minted v3 temp files, normally removed by latexminted (clean, cleanconfig) but left behind when a run is killed
  }

  /**
   * TASK: Clear the files and directories generated by Parsifal in CACHE_PATH.
   *
   * CAVE: These are mass deletions and in the development machine without protection by containers or different users
   * THUS: Make sure we only delete stuff which we really want to delete and be rather conservative on the diverse checks since a typo somewhere else might produce desasters :-(
   *
   * What minted (v3, with package option cache) generates in the output directory CACHE_PATH:
   *   CACHE_PATH/_<JOBHASH>.data.minted     temp file: code and options handed from TeX to latexminted; removed by "latexminted clean" at the end of the run
   *   CACHE_PATH/_<JOBHASH>.config.minted   temp file: capabilities reported by latexminted back to TeX; removed by "latexminted cleanconfig" right away
   *   CACHE_PATH/_minted/                   persistent cache directory, shared by all jobs:
   *     <CODEHASH>.highlight.minted         highlighted LaTeX of one code block (hash over code and options, so identical snippets share a file)
   *     <style>.style.minted                macro definitions of a Pygments style, eg emacs.style.minted
   *     _<JOBHASH>.index.minted             highlight files used by one job; used by "latexminted clean" and by highlightmode=fastfirst
   *   JOBHASH is a hash of the TeX job name. minted v2 used one directory _minted-<jobname> per job instead, which we still clear as well.
   *
   * @return void
   */
  private function clearCacheDir () {
    $VERBOSE = $this->VERBOSE;
    $dir = new DirectoryIterator( CACHE_PATH );                                                                 // iterate the CACHE_PATH
    if ($VERBOSE) danteLog ("Parsifal", "Log was called\n");

    foreach ($dir as $fileinfo) {

      // unlink Parsifal output files and leftover minted temp files
      if ( !$fileinfo->isDot() && $fileinfo->isFile() && file_exists (CACHE_PATH . $fileinfo->getFilename()) && self::isCacheFile ($fileinfo->getFilename()) )
        {  unlink ( CACHE_PATH . $fileinfo->getFilename());  }

      // clear minted cache directories: first the files inside, then the directory itself
      if ( !$fileinfo->isDot() && $fileinfo->isDir() && file_exists (CACHE_PATH . $fileinfo->getFilename()) && self::isMintedCacheDir ($fileinfo->getFilename()) ) {
        // this is a directory, probably of files
        // first iterate the diretory for files, then clear directory itself
        $sub = new DirectoryIterator ( CACHE_PATH.$fileinfo->getFilename() );
        foreach ($sub as $subfile) {
          if (  $subfile->isDot() )    { if ($VERBOSE) {danteLog ("Parsifal", "Skipping sub isDot\n");}  continue; }
          if ( !$subfile->isFile() )  { if ($VERBOSE) {danteLog ("Parsifal", "Skipping not file " .$subfile->getFilename(). "\n");}  continue; }
          if (  !file_exists ( CACHE_PATH . $fileinfo->getFilename(). "/". $subfile->getFilename()) ) { if ($VERBOSE) { danteLog ("Parsifal", "Skipping not exist: "  . CACHE_PATH . $fileinfo->getFilename(). "/". $subfile->getFilename() . "\n");} continue; }

          $ret = unlink (CACHE_PATH . $fileinfo->getFilename() . "/" . $subfile->getFilename());
          if ($VERBOSE) danteLog  ("Parsifal", "UNLINKING: ". CACHE_PATH . $fileinfo->getFilename() . "/" . $subfile->getFilename(). "    " . ($ret ? "SUCCEEDED" : "FAILED") . "\n" );

        } // end inner foreach
        if ( !$fileinfo->isDot() && $fileinfo->isDir() && file_exists (CACHE_PATH . $fileinfo->getFilename()) && self::isMintedCacheDir ($fileinfo->getFilename()) )
          { $ret = rmdir ( CACHE_PATH. $fileinfo->getFilename() );
            if ($VERBOSE) danteLog ("Parsifal", "RMDIR: " . CACHE_PATH. $fileinfo->getFilename() . "   " . ( $ret ? "SUCCEEDED" : "FAILED") . "\n");
          }
         else {
           if ($VERBOSE) danteLog ("Parsifal", "RM SKIPPED: " . CACHE_PATH . $fileinfo->getFilename() . "\n" );
         }
      }  // end if
    }  // end outer foreach
    $this->done[] = 'Parsifal cache files: cleared';
  }

  /**
   * TASK: Clear the Parsifal log and the logs of other Dante extensions.
   *
   * @return void
   */
  private function clearLogs () {
    global $IP;
    if ( file_exists ( LOG_PATH ) ) {unlink ( LOG_PATH );}                                                      // unlink the main log (only if it exists - to prevent any error messages from being displayed)

    // names of other files to be removed
    $otherFiles = array ( "DantePresentations/endpoints/ENDPOINT_LOG",  "DantePresentations/LOGFILE",  "DanteLinks/DANTELINKS-LOGFILE",  "DanteTree/LOGFILE");
    foreach ($otherFiles as $fileName) {
      $full =  $IP. "/extensions/" . $fileName;
      if ( file_exists ($full) ) {unlink ($full);}
    }
    $this->done[] = 'Log files: cleared';
  }

  /**
   * TASK: Clear the sidebar cache file.
   *
   * @return void
   */
  private function clearSidebar () {
    global $IP;
    if ( file_exists ($IP."/sidebarcache") ) { unlink ( $IP."/sidebarcache" ); }
    $this->done[] = 'Sidebar cache: cleared';
  }

  /**
   * TASK: Clear the PHP opcache.
   *
   * Only affects the opcache of the PHP process pool serving this request (php-fpm or mod_php), which is the one that matters for the wiki.
   * Fails if opcache is disabled or if opcache.restrict_api excludes this script.
   *
   * @return void
   */
  private function clearOpcache () {
    if ( !function_exists( 'opcache_reset' ) ) { $this->done[] = 'Opcache: extension not loaded'; return; }    // opcache extension missing
    $status = @opcache_get_status( false );                                                                     // false if opcache disabled or API restricted
    if ( $status === false || empty( $status['opcache_enabled'] ) ) { $this->done[] = 'Opcache: not enabled (or API restricted)'; return; }
    $this->done[] = 'Opcache: ' . ( opcache_reset() ? 'reset scheduled (takes effect for subsequent requests)' : 'FAILED' );
  }

  /**
   * TASK: Touch LocalSettings.php so that MediaWiki invalidates its caches.
   *
   * @return void
   */
  private function touchSettings () {
    global $IP;
    $this->done[] = 'LocalSettings.php: ' . ( touch($IP."/LocalSettings.php") ? 'touched' : 'FAILED' );
  }

}
