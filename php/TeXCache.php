<?php

/** APCu cache for the HTML produced by TeXProcessor::lazyRender, addressed by a cache key supplied by the caller.
 *  Logging goes through TeXProcessor::debugLog; this file is loaded by TexProcessor.php, so that class is always available here.
 */
class TeXCache {

  const ENABLED      = true;    // use the APCu cache at all
  const TTL          = 1000;    // lifetime of a cache entry in seconds
  const VERBOSE      = false;   // write cache hit and miss info into the log file
  const VERBOSE_FULL = false;   // write cache details on every cache access into the log file - CAVE: immense amount of log information

  /**
   * Look up the HTML cached under a cache key.
   *
   * @param string     $key       cache key identifying the entry
   * @param bool       &$found    set to true on a cache hit, false on a miss or when the cache is disabled
   * @param float|null $startTime microtime(true) at the start of the caller, used to log the duration until a hit; null to omit it
   * @return mixed                the cached HTML on a hit, false otherwise
   */
  public static function fetch ($key, &$found, $startTime = null) {
    // cache disabled: always report a miss
    $found = false;
    if (!self::ENABLED) { return false; }

    // look up the entry and log hit or miss
    $cRet = apcu_fetch ($key, $found);
    if ($found) {
      $totalDuration = ($startTime === null ? "(unknown)" : microtime (true) - $startTime);
      if (self::VERBOSE) { TeXProcessor::debugLog ("lazyRender: cache HIT for $key, function call returning after $totalDuration \n"); }
    }
    else {
      if (self::VERBOSE) { TeXProcessor::debugLog ("lazyRender: cache MISS for $key \n"); }
    }
    self::logCacheInfo ();
    return $cRet;
  }

  /**
   * Store HTML under a cache key, so it need not be rebuilt from the files for the next TTL seconds.
   *
   * @param string $key cache key identifying the entry
   * @param string $html HTML generated by lazyRender
   * @return bool        result of apcu_store, false when the cache is disabled
   */
  public static function store ($key, $html) {
    // cache disabled: nothing to do
    if (!self::ENABLED) { return false; }

    // write the entry and log the result
    $cRet = apcu_store ($key, $html, self::TTL);
    if (self::VERBOSE) { TeXProcessor::debugLog ("lazyRenderer: Wrote result for $key into APCU cache, result was $cRet \n"); }
    self::logCacheInfo ();
    return $cRet;
  }

  /**
   * Write the complete APCu cache info into the log file when VERBOSE_FULL is set.
   *
   * @return void
   */
  private static function logCacheInfo () {
    // only in full verbose mode, since the output is huge
    if (self::VERBOSE_FULL) { TeXProcessor::debugLog ("  Cache info is: " . print_r (apcu_cache_info (), true) . "\n\n"); }
  }

}

?>
